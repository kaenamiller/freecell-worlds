// --- asset loading ------------------------------------------------------------
const imageCache = new Map();
const fontCache = new Set();

export function loadImage(url) {
  if (imageCache.has(url)) return imageCache.get(url);
  const p = new Promise((resolve) => {
    const img = new Image();
    img.decoding = 'async';
    img.onload = () => resolve(img);
    img.onerror = () => resolve(null);
    img.src = url;
  });
  imageCache.set(url, p);
  return p;
}

async function loadFont(theme) {
  if (fontCache.has(theme.id)) return;
  fontCache.add(theme.id);
  try {
    // Faces are declared in CSS; this forces them to be ready before canvas drawing.
    await Promise.all([700, 400].map((w) => document.fonts.load(`${w} 40px '${theme.fontFamily}'`)));
  } catch {
    /* falls back to system serif/sans */
  }
}

// Loads every image + font a theme needs. onProgress receives 0..1.
export async function loadThemeAssets(theme, onProgress) {
  const keys = Object.keys(theme.art);
  let done = 0;
  const tick = () => onProgress && onProgress(++done / (keys.length + 1));
  const [, ...imgs] = await Promise.all([
    loadFont(theme).then(tick),
    ...keys.map((k) => loadImage(theme.art[k]).then((i) => (tick(), i))),
  ]);
  const out = {};
  keys.forEach((k, i) => (out[k] = imgs[i]));
  return out;
}
