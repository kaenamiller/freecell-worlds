// Runtime invariants and regression checks, discovered by charm-content-check.mjs.
import { createRun, startBoard, winBoard, pickCharm, runView, loadRun, RUN_VERSION } from '../../js/voyage/run.js';
import { nextChoices } from '../../js/voyage/map.js';

export async function check(h) {
  const { assert, Rules, BoardEffects, CHARMS, baseRules, scoreBoard, kit, clone, fakeBoard, stubAPI } = h;
  const fixture = fakeBoard();
  const run = createRun({ seed: 'kernel-regression' });
  run.boons = ['dev.survey', 'dev.workshop'];
  const cur = startBoard(run, nextChoices(run.map)[0].id, { deal: 1, par: 60 });
  cur.active = [{ id: 'dev.survey', kind: 'boon', strength: 2 }, { id: 'dev.workshop', kind: 'boon', strength: 2 }, { id: 'dev.veil', kind: 'challenge', strength: 2 }];
  const api = stubAPI(fixture.game, { picks: [null, 0, 1] });
  const effects = new BoardEffects(cur.active, { seed: run.seed, boardIndex: 0, api, memo: cur.memo, run });
  effects.setup(fixture.board);
  assert.equal(effects.abilityBonus, 1);
  assert.equal(effects.abilityState('dev.survey').uses, 2);
  assert.equal(effects.abilityState('dev.workshop').uses, 3);
  assert(effects.hasAvailableAbility());
  assert.equal(await effects.useAbility('dev.workshop'), false);
  assert.equal(effects.abilityState('dev.workshop').uses, 3, 'cancel must keep uses');
  assert.equal(await effects.useAbility('dev.workshop'), true);
  assert.equal(fixture.game.history.at(-1).t, 'X');
  const swapped = clone(fixture.game.state);
  const extra = { initial: fixture.initial, rules: baseRules(), boardIdx: 0, elapsed: 601, undosUsed: 2, undosLeft: run.undos };
  assert.deepEqual(kit.replay({ ...extra, history: fixture.game.history }, () => {}), swapped, 'custom move replay');
  const x = fixture.game.undo();
  effects.refundAbility({ id: 'dev.workshop', uses: 3 });
  assert.equal(effects.abilityState('dev.workshop').uses, 3);
  fixture.game.applyDescriptor(x);
  assert.deepEqual(fixture.game.state, swapped, 'custom move JSON replay');
  fixture.game.undo();
  const initialCells = fixture.game.free.length;
  fixture.game.applyCharmMove({ t: 'X', op: 'voyage.cells', count: initialCells + 1 });
  assert.equal(fixture.game.rules.freeCells, initialCells + 1);
  fixture.game.undo();
  assert.equal(fixture.game.rules.freeCells, initialCells);
  assert.equal(fixture.game.free.length, initialCells);
  const hidden = effects.ctxs[2].api.concealed[0];
  effects.reveal([hidden]);
  assert(!effects.ctxs[2].api.concealed.includes(hidden));
  assert.equal(cur.memo['dev.survey'].reveals, 1);
  effects.ctxs[0].api.unmark([cur.memo['dev.survey'].card]);
  effects.ctxs[0].api.badge('saved');
  await effects.useAbility('dev.survey');
  const resumed = new BoardEffects(cur.active, { seed: run.seed, boardIndex: 0, api: stubAPI(fixture.game), memo: clone(cur.memo), run: clone(run) });
  resumed.setup({ ...fixture.board, restored: true });
  assert.equal(resumed.ctxs[0].memo._runtime.badge, 'saved');
  assert.equal(resumed.abilityState('dev.survey').uses, 1);
  assert(!resumed.ctxs[2].api.concealed.includes(hidden), 'resume must not conceal revealed cards');
  assert.deepEqual(resumed.ctxs[0].memo._runtime.marks, {}, 'unmark survives setup/resume');
  resumed.ctxs[2].api.conceal([hidden]);
  assert(resumed.ctxs[2].api.concealed.includes(hidden), 'explicit visibility undo may re-conceal');
  resumed.reveal([hidden]);
  assert.throws(() => { effects.ctxs[0].run.undos = 99; }, TypeError);
  assert.throws(() => { effects.ctxs[0].run.boons.push('x'); }, TypeError);
  run.undos = 0;
  assert(effects.emit('stuck'));
  assert.equal(effects.emit('stuck'), false, 'runMemo rescue cannot be farmed');
  assert.equal(effects.offers(1), 2);
  assert.equal(effects.starCap(extra), 2);
  const sb = scoreBoard(fixture.history, 60, effects, extra);
  const result = winBoard(run, fixture.history, effects, { elapsed: 601, rules: baseRules() });
  assert.equal(result.total, sb.total, 'live and final share context/path');
  assert(result.stars <= 2);
  assert.equal(run.reward.offers.length, Math.min(3, result.stars + 1));
  pickCharm(run, run.reward.offers[0]);
  assert.equal(run.status, 'map');
  const homeRules = { ...baseRules(), startHome: 2, foundationReturn: true };
  const homeGame = new Rules.Game(1, { rules: homeRules });
  assert.equal(scoreBoard([], 60, null, { initial: homeGame.initial }).stat.cards, 8, 'startHome points retained');
  const initialRules = clone(homeGame.rules);
  const ret = homeGame.moveFoundationReturn(0, { kind: 'free', i: 0 });
  assert(ret);
  assert.equal(scoreBoard(homeGame.history, 60, null, { initial: homeGame.initial }).stat.cards, 7);
  assert.deepEqual(kit.replay({ initial: homeGame.initial, history: homeGame.history, rules: initialRules }, () => {}), homeGame.state);
  assert.deepEqual(kit.chainsOf([{t:'F',card:1},{t:'F',card:14},{t:'C'},{t:'F',card:27}]).map((c)=>c.length), [2,1]);
  assert.equal(kit.rankMask(1, 13), 8194); assert.equal(kit.suitMask(0, 3), 9);
  assert.equal(kit.isCourt(13), true); assert.equal(kit.rankName(1), 'Ace');
  // An additive runtime upgrade accepts version-2 saves lacking new fields.
  const old = createRun({ seed: 'old-save' }); delete old.charmMemo;
  const storageDescriptor = Object.getOwnPropertyDescriptor(globalThis, 'localStorage');
  Object.defineProperty(globalThis, 'localStorage', { configurable: true, value: { getItem: () => JSON.stringify(old) } });
  try { assert.equal(loadRun().v, RUN_VERSION); assert.deepEqual(loadRun().charmMemo, {}); } finally { if (storageDescriptor) Object.defineProperty(globalThis, 'localStorage', storageDescriptor); else delete globalThis.localStorage; }
  // Use the dealer's resolved/relaxed rules rather than the original plan.
  const fallback = createRun({ seed: 'relaxed' });
  const resolved = startBoard(fallback, nextChoices(fallback.map)[0].id, { deal: 1, par: 60, rules: homeRules, strength: 0, active: [], relaxed: true });
  assert.equal(resolved.strength, 0); assert.equal(resolved.rules.startHome, 2); assert(resolved.relaxed);
  assert.equal(runView(fallback).current.strength, 0);
  assert(CHARMS['dev.survey']);
}
