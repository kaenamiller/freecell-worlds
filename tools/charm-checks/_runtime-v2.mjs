import { charmText, boonsForTheme } from '../../js/voyage/charms.js';
import { CHARM_FAMILIES } from '../../js/voyage/registry.js';

export async function check(h) {
  const { assert, Rules, BoardEffects, baseRules, clone, stubAPI, kit, assertAvailablePure, checkV2Definitions } = h;
  const game = new Rules.Game(1, { rules: baseRules() });
  const memo = {}, run = { seed: 'v2', status: 'board', boons: ['dev.survey', 'dev.preview', 'dev.window', 'dev.wager'], coins: 17, undos: 0, charmMemo: {}, stickers: {} };
  const active = ['dev.survey', 'dev.preview', 'dev.window', 'dev.reset', 'dev.battery', 'dev.faucet', 'dev.exempt', 'dev.wager'].map((id) => ({id, kind: 'boon', strength: 1, level: id === 'dev.preview' ? 2 : 1}));
  const api = stubAPI(game, { run, memo });
  const fx = new BoardEffects(active, { seed: run.seed, boardIndex: 0, api, memo, run });
  fx.setup({state: clone(game.initial), initial: clone(game.initial)});
  const ctx = fx.ctxs.find((c) => c.id === 'dev.preview');
  assert.deepEqual(Object.keys(ctx.api.abilityUses()),active.map((a) => a.id));
  assert.equal(ctx.api.abilityUses()['dev.preview'],3);
  assert.throws(() => {ctx.api.abilityUses()['dev.preview'] = 99;}, TypeError);
  assert.equal(ctx.level, 2); assert.equal(ctx.family('vision'), 2); assert.equal(ctx.family('fortune'), 1);
  assert.equal(ctx.coins, 17); run.coins++; assert.equal(ctx.coins, 18);
  assert.throws(() => { ctx.coins = 99; }, TypeError);
  assert.equal(fx.ctxs[0].level, 1);
  assert.equal(charmText('dev.preview', 7, {seed: 'v2', level: 2}), 'Preview three moves twice.');
  assert.equal(charmText('dev.preview', 7), 'Preview three moves without playing them.');
  assert(!boonsForTheme('roman').includes('dev.preview'));
  assert(!boonsForTheme(undefined).includes('voyage.stickers'));
  const markedCard = game.tableau[0].at(-1);
  const markMemo = {}, markRun = {...run, stickers:{[markedCard]:'wild'}};
  const markAPI = stubAPI(game);
  const markFx = new BoardEffects([{id:'dev.survey',kind:'boon',strength:1},{id:'voyage.stickers',kind:'boon',strength:1}], {seed:run.seed, boardIndex:0, api:markAPI, memo:markMemo, run:markRun});
  markFx.setup({state:clone(game.initial),initial:clone(game.initial)});
  assert.equal(markAPI.marks[markedCard],'wanted'); assert.equal(markAPI.stickerMarks[markedCard],'sticker-wild');
  markFx.restoreVisuals();
  assert.equal(markAPI.marks[markedCard],'wanted'); assert.equal(markAPI.stickerMarks[markedCard],'sticker-wild');
  markFx.ctxs[0].api.unmark([markedCard]);
  assert(!markAPI.marks[markedCard]); assert.equal(markAPI.stickerMarks[markedCard],'sticker-wild');
  assert(CHARM_FAMILIES.includes('fortune'));
  assert.equal(fx.abilityState('dev.preview').uses, 3, 'level-dependent uses plus abilityBonus');
  assert(fx.abilityState('dev.wager').available);
  assert(!fx.abilityState('dev.reset').available);
  assert(!fx.abilityState('dev.window').available);
  const rules = clone(game.rules);
  assert(await fx.useAbility('dev.wager'));
  assert.equal(run.stickers[1], 'wild'); assert.deepEqual(game.rules, rules);
  const stickers = api.stickers; stickers[1] = 'fool'; assert.equal(api.stickers[1], 'wild');
  assert.deepEqual(ctx.stickers, {}, 'board sticker snapshot stays fixed after a grant');
  assert.equal(await api.solvable(), true);
  assert.equal(await stubAPI(game, {solveResult:false}).solvable(), false);
  assert.equal(await stubAPI(game, {solveResult:null}).solvable(), null);
  assert(api.addSticker(1, 'key')); assert.equal(run.stickers[1], 'key');
  assert(!api.addSticker(0, 'wild')); assert(!api.addSticker(53, 'wild')); assert(!api.addSticker(1, 'wrong'));
  assert.equal(fx.abilityState('dev.battery').uses, 6);
  assert.equal(ctx.api.grantUse('dev.preview', 99), 2);
  assert.equal(ctx.api.grantUse('dev.preview'), 0);
  assert.equal(fx.abilityState('dev.preview').uses, 5);
  assert.equal(ctx.api.grantUse('missing'), 0);
  assert.equal(ctx.api.grantUse('dev.preview', Infinity), 0);
  assert(await fx.useAbility('dev.preview'));
  assert.equal(game.history.length, 0, 'preview applies no move');
  assert(memo['dev.battery'].events.includes('dev.preview'));
  fx.refundAbility({ id: 'dev.preview', uses: 3, grants: 0 });
  assert.equal(fx.abilityState('dev.preview').uses, 5, 'refund preserves subsequently granted uses');
  assert.equal(ctx.api.addUndos(2), 2); assert.equal(ctx.api.addUndos(2), 1); assert.equal(ctx.api.addUndos(1), 0);
  assert.equal(memo._undoGrants, 3); assert.equal(ctx.api.undoGrants, 3); assert.equal(ctx.api.undoCap, 3);
  assert(api.calls.some(([name, message]) => name === 'notify' && message === 'undo cap reached'));
  fx.emit('stuck'); assert.equal(memo._undoGrants, 3);
  assert(api.calls.some(([name, n]) => name === 'addUndos' && n === 4), 'stuck bypasses cap');
  assert(await fx.useAbility('dev.exempt')); assert.equal(memo._undoGrants, 3);
  run.status = 'reward'; assert.equal(ctx.api.addUndos(5), 5); assert.equal(memo._undoGrants, 3);
  ctx.api.addCoins(3); assert.equal(run.coins, 21);
  run.status = 'board'; assert.throws(() => ctx.api.addCoins(1), /sb.addCoins/);
  const move = game.applyDescriptor(Rules.generateMoves(game.state, {rules: game.rules})[0]);
  fx.emit('move', {move, manual:true});
  memo['dev.wager']._runtime.abilityUses = 1;
  assert(!fx.abilityState('dev.wager').available, 'start gate ignores remaining uses after a player move');
  assert(fx.abilityState('dev.reset').available); assert(fx.abilityState('dev.window').available);
  assert(await fx.useAbility('dev.window')); assert(memo._undoWindow);
  assert(!fx.abilityState('dev.window').available);
  assert(kit.paidUndo({})); assert(!kit.paidUndo({free: true})); assert(!kit.paidUndo({reset: true}));
  const saved = clone(memo);
  const resumed = new BoardEffects(active, {seed: run.seed, boardIndex: 0, api, run, memo: saved});
  resumed.setup({state: clone(game.initial), initial: clone(game.initial), restored: true});
  assert.equal(resumed.ctxs.find((c) => c.id === 'dev.preview').api.undoGrants, 3);
  assert(saved._undoWindow); assert.equal(resumed.abilityState('dev.preview').uses, 5);
  game.applyCharmMove({t: 'X', op: 'voyage.cells', count: game.free.length + 1});
  assert(await fx.useAbility('dev.reset'));
  assert.deepEqual(game.state, game.initial); assert.deepEqual(game.rules, rules); assert.equal(game.history.length, 0);
  assert(!fx.abilityState('dev.wager').available, 'reset cannot reopen a start-only ability');
  // Legacy spend/refund hooks ignore free/reset; anchor hooks still receive them.
  const refunds = ['cyber.cache', 'canyon.echo', 'deepstorage.redundancy', 'cyber.challenge', 'library.bookmark'].map((id) => ({id, kind: 'boon', strength: 7}));
  const refundMemo = {}, refundFx = new BoardEffects(refunds, {seed: 'refund', boardIndex: 0, api, run, memo: refundMemo});
  refundFx.setup({state: clone(game.initial), initial: clone(game.initial)});
  refundMemo['library.bookmark'].anchor = 123;
  const calls = api.calls.length;
  refundFx.emit('undo', {reset: true, moves: [move], move});
  refundFx.emit('undo', {free: true, moves: [move], move});
  assert.equal(refundMemo['library.bookmark'].anchor, null);
  assert(!refundMemo['cyber.cache'].refunded); assert(!run.charmMemo['deepstorage.redundancy'].spent);
  assert(!refundMemo['cyber.challenge'].undoCount);
  assert(!api.calls.slice(calls).some(([name]) => name === 'addUndos' || name === 'spendUndos'));
  const winAPI = stubAPI(game);
  const winRun = {status:'board',boons:['dev.weather','dev.battery'],charmMemo:{}}, winMemo = {};
  const winFx = new BoardEffects(['dev.weather','dev.battery'].map((id) => ({id,kind:'boon',strength:1})), {seed:'win-use',boardIndex:0,api:winAPI,run:winRun,memo:winMemo});
  winFx.setup({state:clone(game.initial),initial:clone(game.initial)});
  winAPI.solvable = async () => {winRun.status='won'; winFx.emit('win'); return true;};
  assert(await winFx.useAbility('dev.weather'));
  assert.equal(winRun.charmMemo['dev.battery'].winUses['dev.weather'],0,'on.win counts the in-flight winning ability as spent');
  for (const c of fx.ctxs) assertAvailablePure(h.CHARMS[c.id], c);
  assert.throws(() => assertAvailablePure({id:'impure', ability:{available(c) {c.memo.bad = true; return true;}}}, ctx), /pure/);
  assert.throws(() => assertAvailablePure({id:'impure', ability:{available(c) {c.api.addUndos(1); return true;}}}, ctx), /pure/);
  assert.throws(() => assertAvailablePure({id:'impure', ability:{available(c) {c.rng.int(4); return true;}}}, ctx), /pure/);
  const strict = process.env.STRICT_V2;
  process.env.STRICT_V2 = '1';
  try {
    const good = {id:'test', kind:'boon', family:'fortune', text:'unique', upgrade:'better'};
    checkV2Definitions([good, {id:'hidden', kind:'boon', hidden:true}]);
    assert.throws(() => checkV2Definitions([{...good, family:'bad'}]), /family/);
    assert.throws(() => checkV2Definitions([{...good, upgrade:undefined}]), /upgrade/);
    assert.throws(() => checkV2Definitions([good, {...good,id:'copy'}]), /identical/);
    assert.throws(() => checkV2Definitions([{id:'curse',kind:'challenge'}]), /pressure/);
  } finally { if (strict == null) delete process.env.STRICT_V2; else process.env.STRICT_V2 = strict; }
}
